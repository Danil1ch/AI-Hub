const FALLBACK_PATH =
  'M9.813 15.904L9 18.75l-.813-2.846a4.5 4.5 0 00-3.09-3.09L2.25 12l2.846-.813a4.5 4.5 0 003.09-3.09L9 5.25l.813 2.846a4.5 4.5 0 003.09 3.09L15.75 12l-2.846.813a4.5 4.5 0 00-3.09 3.09z'

export function ServiceBrandIcon({
  id,
  accent,
  className,
  width = 18,
  height = 18,
  ...svgProps
}: { id: ServiceId; accent: string } & SVGProps<SVGSVGElement>) {
  const base = `block shrink-0 ${className ?? ''}`
  const rid = useId().replace(/:/g, '')

  if (id === 'deepseek') {
    return (
      <svg
        viewBox="0 0 56 41.5"
        aria-hidden
        className={base}
        width={width}
        height={height}
        preserveAspectRatio="xMidYMid meet"
        {...svgProps}
      >
        <path fill="#4d6bfe" d={DEEPSEEK_WHALE_D} />
      </svg>
    )
  }

  if (id === 'qwen') {
    return <QwenIcon className={base} width={width} height={height} uid={rid} {...svgProps} />
  }

  if (id === 'kimi') {
    return <KimiIcon className={base} width={width} height={height} {...svgProps} />
  }

  if (id === 'character') {
    return <CharacterIcon className={base} width={width} height={height} {...svgProps} />
  }

  if (id === 'mistral') {
    const mg = `ms_${rid}`
    return (
      <svg viewBox="0 0 24 24" aria-hidden className={base} width={width} height={height} {...svgProps}>
        <defs>
          <linearGradient id={mg} gradientUnits="objectBoundingBox" x1="0" y1="0" x2="0" y2="1">
            <stop offset="0%" stopColor="#F5D110" />
            <stop offset="20%" stopColor="#F5D110" />
            <stop offset="20%" stopColor="#FF9E00" />
            <stop offset="40%" stopColor="#FF9E00" />
            <stop offset="40%" stopColor="#FF6900" />
            <stop offset="60%" stopColor="#FF6900" />
            <stop offset="60%" stopColor="#FF2D00" />
            <stop offset="80%" stopColor="#FF2D00" />
            <stop offset="80%" stopColor="#E60000" />
            <stop offset="100%" stopColor="#E60000" />
          </linearGradient>
        </defs>
        <path fill={`url(#${mg})`} fillRule="evenodd" clipRule="evenodd" d={MISTRAL_D} />
      </svg>
    )
  }

  if (id === 'labs') {
    return (
      <img
        src={googleLabsSrc}
        alt=""
        aria-hidden
        draggable={false}
        className={`${base} object-contain`}
        width={width}
        height={height}
      />
    )
  }

  if (id === 'gemini') {
    return <GeminiIcon className={base} width={width} height={height} gid={rid} {...svgProps} />
  }

  const d = PATHS_MONO[id]
  const fill = MONO_PATH_FILL[id]
  if (d && fill) {
    return (
      <svg viewBox="0 0 24 24" aria-hidden className={base} width={width} height={height} {...svgProps}>
        <path fill={fill} d={d} />
      </svg>
    )
  }

  return (
    <svg
      viewBox="0 0 24 24"
      aria-hidden
      className={base}
      width={width}
      height={height}
      style={{ color: accent }}
      {...svgProps}
    >
      <path fill="currentColor" d={FALLBACK_PATH} />
    </svg>
  )
}

